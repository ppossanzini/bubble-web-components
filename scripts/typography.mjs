import { mkdir, copyFile, writeFile, readFile } from "node:fs/promises";

// Values follow the recorded Material token set 34.0.21, static-font weights.
const roles = [
  ["display-large", "brand", 400, 57, 64, -0.25],
  ["display-medium", "brand", 400, 45, 52, 0],
  ["display-small", "brand", 400, 36, 44, 0],
  ["headline-large", "brand", 400, 32, 40, 0],
  ["headline-medium", "brand", 400, 28, 36, 0],
  ["headline-small", "brand", 400, 24, 32, 0],
  ["title-large", "brand", 400, 22, 28, 0],
  ["title-medium", "plain", 500, 16, 24, 0.15],
  ["title-small", "plain", 500, 14, 20, 0.1],
  ["body-large", "plain", 400, 16, 24, 0.5],
  ["body-medium", "plain", 400, 14, 20, 0.25],
  ["body-small", "plain", 400, 12, 16, 0.4],
  ["label-large", "plain", 500, 14, 20, 0.1],
  ["label-medium", "plain", 500, 12, 16, 0.5],
  ["label-small", "plain", 500, 11, 16, 0.5],
];
let css = "/* Generated by scripts/typography.mjs. Do not edit. */\n";
await mkdir("public/fonts", { recursive: true });
for (const weight of [400, 500, 700]) {
  const faces = await readFile(
    `node_modules/@fontsource/roboto/${weight}.css`,
    "utf8",
  );
  for (const match of faces.matchAll(/@font-face\s*\{[^}]+\}/g)) {
    const face = match[0];
    const file = face.match(/\.\/files\/([^')]+\.woff2)/)?.[1];
    if (!file) throw new Error("Roboto font face has no WOFF2 source.");
    await copyFile(
      `node_modules/@fontsource/roboto/files/${file}`,
      `public/fonts/${file}`,
    );
    css +=
      face.replace(
        /src:[^;]+;/,
        `src: url("./fonts/${file}") format("woff2");`,
      ) + "\n";
  }
}
await copyFile(
  "node_modules/@fontsource/roboto/LICENSE",
  "public/fonts/LICENSE",
);
css +=
  ":root { --md-ref-typeface-brand: Roboto, sans-serif; --md-ref-typeface-plain: Roboto, sans-serif; }\n:root, [lang], [data-language-height] {\n";
const classes = [];
for (const emphasized of [false, true]) {
  for (const [name, face, baseWeight, size, height, tracking] of roles) {
    const weight = emphasized ? (baseWeight === 500 ? 700 : 500) : baseWeight;
    const prefix = `--md-sys-typescale-${emphasized ? "emphasized-" : ""}${name}`;
    css += `${prefix}-font-family: var(--md-ref-typeface-${face});\n`;
    for (const [key, value] of Object.entries({
      weight,
      size: `${size / 16}rem`,
      "line-height": `calc(${height / 16}rem * var(--bubble-language-line-height-scale, 1))`,
      tracking: `${tracking / 16}rem`,
    }))
      css += `${prefix}-${key}: ${value};\n`;
    css += `${prefix}-font: var(${prefix}-weight) var(${prefix}-size)/var(${prefix}-line-height) var(${prefix}-font-family);\n`;
    classes.push(
      `.md-type-${emphasized ? "emphasized-" : ""}${name} { font: var(${prefix}-font); letter-spacing: var(${prefix}-tracking); }\n`,
    );
  }
}
css += "}\n" + classes.join("");
css += `
/* Project language-height policy; ratios are not exact Material token values. */
:root, [lang], [data-language-height] {
  --bubble-language-line-height-scale: 1.07;
}
:is(:lang(en), :lang(it), :lang(fr), :lang(de), :lang(es), :lang(pt), :lang(el), :lang(ru), :lang(uk), :lang(he)),
[data-language-height="small"] { --bubble-language-line-height-scale: 1; }
:is(:lang(my), :lang(te)), [data-language-height="large"] { --bubble-language-line-height-scale: 1.3; }
:lang(ur), [data-language-height="extra-large"] { --bubble-language-line-height-scale: 2; }
[data-language-height="medium"] { --bubble-language-line-height-scale: 1.07; }
.md-numerals-tabular { font-variant-numeric: lining-nums tabular-nums; }
.md-text-link {
  color: var(--md-sys-color-primary);
  text-decoration-line: underline;
  text-underline-offset: .15em;
  overflow-wrap: anywhere;
}
.md-text-link--tertiary { color: var(--md-sys-color-tertiary); }
.md-text-link:focus-visible {
  outline: var(--md-sys-state-focus-indicator-thickness) solid currentColor;
  outline-offset: 2px;
}
`;
await writeFile("public/typography.css", css);
console.log("Generated 30 typography styles and local Roboto fonts.");
